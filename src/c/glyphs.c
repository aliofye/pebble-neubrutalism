const DigitGlyph *glyph_for_char(char c) {
  if (c >= '0' && c <= '9') {
    return &s_digit_glyphs[c - '0'];
  }
  if (c == ':') {
    return &s_digit_glyphs[10];
  }
  return NULL;
}

int glyph_width(const DigitGlyph *glyph) {
  return glyph ? (int)strlen(glyph->rows[0]) : 0;
}